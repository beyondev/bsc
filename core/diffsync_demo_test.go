type txKind int

const (
	kindTransfer txKind = iota
	kindDex
	kindStorage
	kindCompute
)

// txMix is the share of each transaction kind, in percent.
type txMix [4]int

var (
	mixTransfer     = txMix{100, 0, 0, 0}
	mixDex          = txMix{0, 100, 0, 0}
	mixStorage      = txMix{0, 0, 100, 0}
	mixCompute      = txMix{0, 0, 0, 100}
	mixMainnetLike  = txMix{45, 35, 15, 5}
	demoWorkloadMix = map[string]txMix{
		"transfer": mixTransfer,
		"dex":      mixDex,
		"storage":  mixStorage,
		"compute":  mixCompute,
		"mixed":    mixMainnetLike,
	}
	demoWorkloadOrder = []string{"transfer", "dex", "storage", "compute", "mixed"}
)

var (
	dexAddr     = common.HexToAddress("0xde00000000000000000000000000000000000001")
	storageAddr = common.HexToAddress("0xde00000000000000000000000000000000000002")
	computeAddr = common.HexToAddress("0xde00000000000000000000000000000000000003")
)

const (
	dexPairs          = 5000 // distinct pair slots the dex contract writes
	computeIterations = 500  // keccak rounds per compute call
	storageSlotsPerTx = 8
	attestors         = 21
)

// dexCode bumps two hot slots (a counter and a reserve), the caller's slot and
// one of dexPairs pair slots: a few slots shared by every transaction plus some
// spread out, like a busy AMM.
func dexCode() []byte {
	return program.New().
		Push(0).Op(vm.SLOAD).Push(1).Op(vm.ADD).Push(0).Op(vm.SSTORE).
		Push(1).Op(vm.SLOAD).Push(0).Op(vm.CALLDATALOAD).Op(vm.ADD).Push(1).Op(vm.SSTORE).
		Op(vm.CALLER).Op(vm.SLOAD).Push(1).Op(vm.ADD).Op(vm.CALLER).Op(vm.SSTORE).
		Op(vm.NUMBER).Push(32).Op(vm.CALLDATALOAD).Op(vm.SSTORE).
		Op(vm.STOP).Bytes()
}

// storageCode writes storageSlotsPerTx fresh slots starting at the key given in
// calldata.
func storageCode() []byte {
	p := program.New()
	for i := 0; i < storageSlotsPerTx; i++ {
		p.Op(vm.NUMBER).Push(i).Op(vm.ADD).Push(0).Op(vm.CALLDATALOAD).Push(i).Op(vm.ADD).Op(vm.SSTORE)
	}
	return p.Op(vm.STOP).Bytes()
}

// computeCode hashes in a loop and stores only the result.
func computeCode() []byte {
	p := program.New().Push(0)
	p, loop := p.Jumpdest()
	p.Push(64).Push(0).Op(vm.KECCAK256).Push(0).Op(vm.MSTORE).
		Push(1).Op(vm.ADD).
		Op(vm.DUP1).Push(computeIterations).Op(vm.GT).Push(loop).Op(vm.JUMPI).
		Op(vm.POP).Push(0).Op(vm.MLOAD).Push(0).Op(vm.SSTORE).Op(vm.STOP)
	return p.Bytes()
}

type diffWorkloadConfig struct {
	Blocks      int
	TxsPerBlock int
	Prefill     int
	Mix         txMix
}

// diffWorkload is a generated chain together with what a diff-serving peer
// would hand out for it.
type diffWorkload struct {
	cfg      diffWorkloadConfig
	genesis  *Genesis
	blocks   types.Blocks
	diffs    [][]byte // RLP of each block's StateDiff
	receipts [][]byte // storage-format RLP of each block's receipts
	bodies   []int    // RLP size of each block
	hashes   []common.Hash

	blsPubs []blscommon.PublicKey
	blsSigs []blscommon.Signature // aggregate attestation over each diff hash
}

func prefillAddr(i int) common.Address {
	var b [8]byte
	binary.BigEndian.PutUint64(b[:], uint64(i))
	return common.BytesToAddress(crypto.Keccak256(b[:])[12:])
}

func newDiffWorkload(t testing.TB, cfg diffWorkloadConfig) *diffWorkload {
	t.Helper()
	config := *params.AllEthashProtocolChanges
	senders := max(cfg.TxsPerBlock*4, 64)
	keys := make([]*ecdsa.PrivateKey, senders)
	alloc := make(types.GenesisAlloc, senders+cfg.Prefill+3)
	funds := new(big.Int).Mul(big.NewInt(1e9), big.NewInt(params.Ether))
	for i := range keys {
		var seed [32]byte
		binary.BigEndian.PutUint64(seed[24:], uint64(i+1))
		keys[i], _ = crypto.ToECDSA(crypto.Keccak256(seed[:]))
		alloc[crypto.PubkeyToAddress(keys[i].PublicKey)] = types.Account{Balance: funds}
	}
	for i := 0; i < cfg.Prefill; i++ {
		alloc[prefillAddr(i)] = types.Account{Balance: big.NewInt(params.Ether)}
	}
	// Pre-existing storage, so that writes land in a non-trivial trie.
	dexStorage := make(map[common.Hash]common.Hash, cfg.Prefill/2+dexPairs)
	storStorage := make(map[common.Hash]common.Hash, cfg.Prefill/2)
	for i := 0; i < cfg.Prefill/2; i++ {
		k := crypto.Keccak256Hash(prefillAddr(i).Bytes())
		dexStorage[k] = common.BigToHash(big.NewInt(int64(i + 1)))
		storStorage[k] = common.BigToHash(big.NewInt(int64(i + 1)))
	}
	alloc[dexAddr] = types.Account{Code: dexCode(), Balance: big.NewInt(0), Storage: dexStorage}
	alloc[storageAddr] = types.Account{Code: storageCode(), Balance: big.NewInt(0), Storage: storStorage}
	alloc[computeAddr] = types.Account{Code: computeCode(), Balance: big.NewInt(0)}

	genesis := &Genesis{Config: &config, Alloc: alloc, GasLimit: 2_000_000_000, BaseFee: big.NewInt(params.InitialBaseFee)}
	signer := types.LatestSigner(&config)
	rng := rand.New(rand.NewSource(1))
	sender := 0
	pickKind := func() txKind {
		r := rng.Intn(100)
		for k, share := range cfg.Mix {
			if r < share {
				return txKind(k)
			}
			r -= share
		}
		return kindTransfer
	}
	_, blocks, receipts := GenerateChainWithGenesis(genesis, ethash.NewFaker(), cfg.Blocks, func(i int, gen *BlockGen) {
		gasPrice := new(big.Int).Add(new(big.Int).Mul(gen.BaseFee(), big.NewInt(2)), big.NewInt(1))
		for j := 0; j < cfg.TxsPerBlock; j++ {
			key := keys[sender%senders]
			sender++
			from := crypto.PubkeyToAddress(key.PublicKey)
			tx := &types.LegacyTx{Nonce: gen.TxNonce(from), GasPrice: gasPrice}
			switch pickKind() {
			case kindTransfer:
				to := prefillAddr(rng.Intn(max(cfg.Prefill, 1)))
				if rng.Intn(10) == 0 {
					to = common.BigToAddress(new(big.Int).SetUint64(rng.Uint64() | 1<<60))
				}
				tx.To, tx.Gas, tx.Value = &to, 21000, big.NewInt(1)
			case kindDex:
				data := make([]byte, 64)
				data[31] = byte(rng.Intn(100) + 1)
				binary.BigEndian.PutUint64(data[56:], uint64(rng.Intn(dexPairs))+1)
				tx.To, tx.Gas, tx.Data = &dexAddr, 120_000, data
			case kindStorage:
				data := make([]byte, 32)
				rng.Read(data)
				tx.To, tx.Gas, tx.Data = &storageAddr, 60_000+storageSlotsPerTx*23_000, data
			case kindCompute:
				tx.To, tx.Gas = &computeAddr, 400_000
			}
			signed, err := types.SignNewTx(key, signer, tx)
			if err != nil {
				panic(err)
			}
			gen.AddTx(signed)
		}
	})

	// Replay on a source chain to record the write sets the way a serving
	// node would.
	w := &diffWorkload{cfg: cfg, genesis: genesis, blocks: blocks}
	recorded := make(map[common.Hash][]byte, len(blocks))
	src, err := NewBlockChain(rawdb.NewMemoryDatabase(), genesis, ethash.NewFaker(), DefaultConfig().WithStateScheme(rawdb.PathScheme))
	if err != nil {
		t.Fatal(err)
	}
	defer src.Stop()
	src.SetStateDiffRecorder(func(block *types.Block, diff *types.StateDiff) {
		enc, err := rlp.EncodeToBytes(diff)
		if err != nil {
			panic(err)
		}
		recorded[block.Hash()] = enc
	})
	if n, err := src.InsertChain(blocks); err != nil {
		t.Fatalf("source import failed at %d: %v", n, err)
	}
	for i, b := range blocks {
		enc, ok := recorded[b.Hash()]
		if !ok {
			t.Fatalf("no diff recorded for block %d", b.NumberU64())
		}
		w.diffs = append(w.diffs, enc)
		stored := make([]*types.ReceiptForStorage, len(receipts[i]))
		for j, r := range receipts[i] {
			stored[j] = (*types.ReceiptForStorage)(r)
		}
		renc, err := rlp.EncodeToBytes(stored)
		if err != nil {
			t.Fatal(err)
		}
		w.receipts = append(w.receipts, renc)
		benc, _ := rlp.EncodeToBytes(b)
		w.bodies = append(w.bodies, len(benc))
		var d types.StateDiff
		if err := rlp.DecodeBytes(enc, &d); err != nil {
			t.Fatal(err)
		}
		w.hashes = append(w.hashes, d.Hash())
	}
	return w
}

// attest signs every diff hash with attestors BLS keys and aggregates the
// signatures, standing in for a validator attestation or a DX ExecCert.
func (w *diffWorkload) attest(t testing.TB) {
	secrets := make([]blscommon.SecretKey, attestors)
	w.blsPubs = make([]blscommon.PublicKey, attestors)
	for i := range secrets {
		sk, err := bls.RandKey()
		if err != nil {
			t.Fatal(err)
		}
		secrets[i], w.blsPubs[i] = sk, sk.PublicKey()
	}
	for _, h := range w.hashes {
		sigs := make([]blscommon.Signature, attestors)
		for i, sk := range secrets {
			sigs[i] = sk.Sign(h[:])
		}
		w.blsSigs = append(w.blsSigs, bls.AggregateSignatures(sigs))
	}
}

// verifyAttestation checks the aggregate signature over block i's diff hash.
func (w *diffWorkload) verifyAttestation(i int) error {
	if !w.blsSigs[i].FastAggregateVerify(w.blsPubs, w.hashes[i]) {
		return errors.New("bad attestation")
	}
	return nil
}

// payload decodes block i's diff and receipts as a syncing node would after
// downloading them.
func (w *diffWorkload) payload(i int, attested bool) *BlockDiffPayload {
	var diff types.StateDiff
	if err := rlp.DecodeBytes(w.diffs[i], &diff); err != nil {
		panic(err)
	}
	var stored []*types.ReceiptForStorage
	if err := rlp.DecodeBytes(w.receipts[i], &stored); err != nil {
		panic(err)
	}
	receipts := make(types.Receipts, len(stored))
	for j, r := range stored {
		receipts[j] = (*types.Receipt)(r)
	}
	p := &BlockDiffPayload{Diff: &diff, Receipts: receipts}
	if attested {
		p.Attested = w.hashes[i]
	}
	return p
}

func (w *diffWorkload) payloads(attested bool) []*BlockDiffPayload {
	out := make([]*BlockDiffPayload, len(w.blocks))
	for i := range out {
		out[i] = w.payload(i, attested)
	}
	return out
}

// newSyncChain opens a fresh on-disk chain (pebble, path scheme) holding only
// the genesis state.
func (w *diffWorkload) newSyncChain(t testing.TB, dir string) *BlockChain {
	t.Helper()
	pdb, err := pebble.New(dir, 512, 128, "", false)
	if err != nil {
		t.Fatal(err)
	}
	db := rawdb.NewDatabase(pdb)
	bc, err := NewBlockChain(db, w.genesis, ethash.NewFaker(), DefaultConfig().WithStateScheme(rawdb.PathScheme))
	if err != nil {
		t.Fatal(err)
	}
	return bc
}

// newScratchChain is newSyncChain in a directory that is removed as soon as
// the returned function is called, so the demo does not keep every database
// until the test ends.
func (w *diffWorkload) newScratchChain(t testing.TB) (*BlockChain, func()) {
	dir, err := os.MkdirTemp("", "diffsync-demo")
	if err != nil {
		t.Fatal(err)
	}
	bc := w.newSyncChain(t, dir)
	return bc, func() {
		bc.Stop()
		os.RemoveAll(dir)
	}
}

