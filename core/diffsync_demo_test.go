// Diff-sync demo: compares importing a range of blocks by execution (current
// full sync) with importing them from state diffs, per block or in merged
// segments, with and without write-set attestations.
//
// The demo is skipped unless BSC_DIFFSYNC_DEMO=1. Knobs:
//
//	DEMO_BLOCKS     blocks per workload (default 512)
//	DEMO_TXS        transactions per block (default 400)
//	DEMO_PREFILL    pre-existing accounts and storage slots (default 200000)
//	DEMO_WORKLOADS  comma-separated subset of transfer,dex,storage,compute,mixed
//	DEMO_OUT        JSON results file (default diffsync-demo.json in the temp dir)
//
// The peer side is in-process: blocks, receipts and diffs are generated by a
// source chain, encoded as they would travel on the wire, and decoded inside
// the timed section. Network transfer is not simulated here; the byte counts
// are reported so that bandwidth limits can be applied afterwards.

