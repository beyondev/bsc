func envInt(name string, def int) int {
	if v, err := strconv.Atoi(os.Getenv(name)); err == nil && v > 0 {
		return v
	}
	return def
}

const demoChunk = 128

func TestDiffSyncDemo(t *testing.T) {
	if os.Getenv("BSC_DIFFSYNC_DEMO") != "1" {
		t.Skip("set BSC_DIFFSYNC_DEMO=1 to run the diff-sync demo")
	}
	blocks := envInt("DEMO_BLOCKS", 512)
	txs := envInt("DEMO_TXS", 400)
	prefill := envInt("DEMO_PREFILL", 200000)
	names := demoWorkloadOrder
	if v := os.Getenv("DEMO_WORKLOADS"); v != "" {
		names = strings.Split(v, ",")
	}
	out := os.Getenv("DEMO_OUT")
	if out == "" {
		out = filepath.Join(os.TempDir(), "diffsync-demo.json")
	}
	var results []demoWorkloadResult
	for _, name := range names {
		mix, ok := demoWorkloadMix[name]
		if !ok {
			t.Fatalf("unknown workload %q", name)
		}
		start := time.Now()
		w := newDiffWorkload(t, diffWorkloadConfig{Blocks: blocks, TxsPerBlock: txs, Prefill: prefill, Mix: mix})
		w.attest(t)
		t.Logf("workload %s generated in %v", name, time.Since(start))
		res := runDemoWorkload(t, name, w)
		if name == "mixed" {
			res.Attacks = runDemoAttacks(t, w)
		}
		results = append(results, res)
		for _, m := range res.Modes {
			t.Logf("%-9s %-24s %8.2f ms/block %8.1f blocks/s root ok=%v %s", name, m.Mode, m.MsPerBlock, m.BlocksPerS, m.RootMatches, m.Note)
		}
		enc, _ := json.MarshalIndent(results, "", "  ")
		if err := os.WriteFile(out, enc, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	t.Logf("results written to %s", out)
}

func runDemoWorkload(t *testing.T, name string, w *diffWorkload) demoWorkloadResult {
	n := len(w.blocks)
	res := demoWorkloadResult{Name: name, Blocks: n, TxsPerBlock: w.cfg.TxsPerBlock,
		MergedRatio: map[string]float64{}, MergedBytes: map[string]float64{}}
	var gas uint64
	var accts, slots int
	decoded := make([]*types.StateDiff, n)
	for i, b := range w.blocks {
		gas += b.GasUsed()
		res.BodyBytes += float64(w.bodies[i])
		res.ReceiptBytes += float64(len(w.receipts[i]))
		res.DiffBytes += float64(len(w.diffs[i]))
		decoded[i] = w.payload(i, false).Diff
		a, s := decoded[i].Keys()
		accts += a
		slots += s
	}
	res.GasPerBlock = float64(gas) / float64(n)
	res.BodyBytes /= float64(n)
	res.ReceiptBytes /= float64(n)
	res.DiffBytes /= float64(n)
	res.DiffAccounts = float64(accts) / float64(n)
	res.DiffSlots = float64(slots) / float64(n)
	for _, m := range []int{8, 32, 128, 512} {
		if m > n {
			continue
		}
		var sumKeys, mergedKeys, mergedBytes int
		for i := 0; i+m <= n; i += m {
			for _, d := range decoded[i : i+m] {
				a, s := d.Keys()
				sumKeys += a + s
			}
			merged := types.MergeStateDiffs(decoded[i : i+m])
			a, s := merged.Keys()
			mergedKeys += a + s
			enc, _ := rlp.EncodeToBytes(merged)
			mergedBytes += len(enc)
		}
		segs := n / m
		res.MergedRatio[strconv.Itoa(m)] = float64(mergedKeys) / float64(sumKeys)
		res.MergedBytes[strconv.Itoa(m)] = float64(mergedBytes) / float64(segs*m)
	}
	{
		start := time.Now()
		for i := 0; i < 50; i++ {
			if err := w.verifyAttestation(i % n); err != nil {
				t.Fatal(err)
			}
		}
		res.BLSVerifyMicro = float64(time.Since(start).Microseconds()) / 50
	}

	// Execution is the reference for the final root.
	execRes, want := runDemoMode(t, w, "exec", func(bc *BlockChain, from, to int) error {
		_, err := bc.InsertChain(w.blocks[from:to])
		return err
	}, demoChunk, common.Hash{})
	res.Modes = append(res.Modes, execRes)

	res.Modes = append(res.Modes, resultOnly(runDemoMode(t, w, "diff-per-block", func(bc *BlockChain, from, to int) error {
		payloads := make([]*BlockDiffPayload, 0, to-from)
		for i := from; i < to; i++ {
			payloads = append(payloads, w.payload(i, false))
		}
		_, err := bc.InsertChainWithDiffs(w.blocks[from:to], payloads)
		return err
	}, demoChunk, want)))

	res.Modes = append(res.Modes, resultOnly(runDemoMode(t, w, "diff-per-block+attest", func(bc *BlockChain, from, to int) error {
		payloads := make([]*BlockDiffPayload, 0, to-from)
		for i := from; i < to; i++ {
			if err := w.verifyAttestation(i); err != nil {
				return err
			}
			payloads = append(payloads, w.payload(i, true))
		}
		_, err := bc.InsertChainWithDiffs(w.blocks[from:to], payloads)
		return err
	}, demoChunk, want)))

	for _, m := range []int{32, 128, 512} {
		if m > n {
			continue
		}
		for _, attested := range []bool{false, true} {
			mode := fmt.Sprintf("segment-%d", m)
			if attested {
				mode += "+attest"
			}
			res.Modes = append(res.Modes, resultOnly(runDemoMode(t, w, mode, func(bc *BlockChain, from, to int) error {
				payloads := make([]*BlockDiffPayload, 0, to-from)
				for i := from; i < to; i++ {
					if attested {
						if err := w.verifyAttestation(i); err != nil {
							return err
						}
					}
					payloads = append(payloads, w.payload(i, attested))
				}
				return bc.InsertSegmentWithDiff(w.blocks[from:to], payloads, attested)
			}, m, want)))
		}
	}
	return res
}

// resultOnly drops the root returned by runDemoMode.
func resultOnly(r demoModeResult, _ common.Hash) demoModeResult { return r }

// runDemoMode imports the workload into a fresh chain in steps of chunk blocks
// and times it. Opening the chain (genesis commit) is not timed.
func runDemoMode(t *testing.T, w *diffWorkload, mode string, step func(bc *BlockChain, from, to int) error, chunk int, want common.Hash) (demoModeResult, common.Hash) {
	bc, done := w.newScratchChain(t)
	defer done()
	res := demoModeResult{Mode: mode}
	n := len(w.blocks)
	var gas uint64
	start := time.Now()
	chunkStart := start
	for from := 0; from < n; from += chunk {
		to := min(from+chunk, n)
		if err := step(bc, from, to); err != nil {
			t.Fatalf("%s: blocks %d-%d: %v", mode, from, to, err)
		}
		for _, b := range w.blocks[from:to] {
			gas += b.GasUsed()
		}
		// Record per-128-block timings regardless of the step size.
		if to%demoChunk == 0 || to == n {
			now := time.Now()
			res.ChunkMs = append(res.ChunkMs, float64(now.Sub(chunkStart).Microseconds())/1000)
			chunkStart = now
		}
	}
	elapsed := time.Since(start)
	root := bc.CurrentBlock().Root
	res.Seconds = elapsed.Seconds()
	res.MsPerBlock = float64(elapsed.Microseconds()) / 1000 / float64(n)
	res.BlocksPerS = float64(n) / elapsed.Seconds()
	res.MgasPerS = float64(gas) / 1e6 / elapsed.Seconds()
	res.RootMatches = want == (common.Hash{}) || root == want
	if bc.CurrentBlock().Hash() != w.blocks[n-1].Hash() {
		t.Fatalf("%s: head %x, want %x", mode, bc.CurrentBlock().Hash(), w.blocks[n-1].Hash())
	}
	if !res.RootMatches {
		t.Errorf("%s: root %x, want %x", mode, root, want)
	}
	return res, root
}

// runDemoAttacks feeds bad diffs and records what each mode does with them.
func runDemoAttacks(t *testing.T, w *diffWorkload) map[string]string {
	out := make(map[string]string)
	n := len(w.blocks)
	seg := 32
	k := seg + seg/2 // a block inside the second segment

	// 1. A wrong final value in one block, per-block mode: refused at that
	// block, which is then executed instead.
	{
		bc, cleanup := w.newScratchChain(t)
		payloads := w.payloads(false)
		payloads[k] = tamperFinalWrite(payloads[k])
		start := time.Now()
		done, rejected := 0, 0
		for done < n {
			m, err := bc.InsertChainWithDiffs(w.blocks[done:], payloads[done:])
			done += m
			if err == nil {
				break
			}
			if !errors.Is(err, ErrDiffRejected) {
				t.Fatal(err)
			}
			rejected++
			if _, err := bc.InsertChain(w.blocks[done : done+1]); err != nil {
				t.Fatal(err)
			}
			done++
		}
		out["per_block_wrong_value"] = fmt.Sprintf("rejected %d diff(s) at block %d, executed it instead; head reached=%v; %.1f ms total",
			rejected, k+1, bc.CurrentBlock().Hash() == w.blocks[n-1].Hash(), float64(time.Since(start).Microseconds())/1000)
		cleanup()
	}

	// 2. A wrong value in the last block of a segment (so no later block in the
	// segment overwrites it), segment mode without attestation: the whole
	// segment fails the root check and is redone block by block to find the
	// bad diff, which is then executed.
	{
		bc, cleanup := w.newScratchChain(t)
		payloads := w.payloads(false)
		bad := 2*seg - 1
		payloads[bad] = tamperFinalWrite(payloads[bad])
		start := time.Now()
		failed, redone := 0, 0
		for from := 0; from < n; from += seg {
			to := min(from+seg, n)
			err := bc.InsertSegmentWithDiff(w.blocks[from:to], payloads[from:to], false)
			if err == nil {
				continue
			}
			if !errors.Is(err, ErrDiffRejected) {
				t.Fatal(err)
			}
			failed++
			for i := from; i < to; {
				m, err := bc.InsertChainWithDiffs(w.blocks[i:to], payloads[i:to])
				i += m
				redone += m
				if err != nil {
					if !errors.Is(err, ErrDiffRejected) {
						t.Fatalf("locating bad diff: %v", err)
					}
					if _, err := bc.InsertChain(w.blocks[i : i+1]); err != nil {
						t.Fatal(err)
					}
					i++
				}
			}
		}
		out["segment_wrong_value"] = fmt.Sprintf("%d segment(s) of %d failed the root check; %d blocks redone from per-block diffs and the bad block %d executed; head reached=%v; %.1f ms total",
			failed, seg, redone, bad+1, bc.CurrentBlock().Hash() == w.blocks[n-1].Hash(), float64(time.Since(start).Microseconds())/1000)
		cleanup()
	}

	// 3. A wrong value that a later block overwrites (the dex counter slot is
	// written in every block). Per-block mode and attested segments catch it;
	// an unattested segment cannot.
	cancel := func() []*BlockDiffPayload {
		payloads := w.payloads(true)
		cp := *payloads[k]
		cp.Diff = copyDiff(cp.Diff)
		for i := range cp.Diff.Accounts {
			a := &cp.Diff.Accounts[i]
			if a.Address != dexAddr {
				continue
			}
			for j := range a.Storage {
				if a.Storage[j].Key == (common.Hash{}) {
					a.Storage[j].Value = common.HexToHash("0xbad")
				}
			}
		}
		payloads[k] = &cp
		return payloads
	}
	for _, c := range []struct {
		name     string
		attested bool
		perBlock bool
	}{{"cancel_out_per_block", false, true}, {"cancel_out_segment", false, false}, {"cancel_out_segment_attested", true, false}} {
		bc, cleanup := w.newScratchChain(t)
		payloads := cancel()
		if !c.attested {
			for _, p := range payloads {
				p.Attested = common.Hash{}
			}
		}
		var err error
		if c.perBlock {
			_, err = bc.InsertChainWithDiffs(w.blocks[:k+seg], payloads[:k+seg])
		} else {
			for from := 0; from < k+seg && err == nil; from += seg {
				err = bc.InsertSegmentWithDiff(w.blocks[from:from+seg], payloads[from:from+seg], c.attested)
			}
		}
		if err != nil {
			out[c.name] = "rejected: " + err.Error()
		} else {
			out[c.name] = "accepted (the final root matched)"
		}
		cleanup()
	}
	return out
}
